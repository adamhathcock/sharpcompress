// Pure.DI cannot see methods emitted by another source generator. Only the sync signatures
// generated by Zomp are declared here; Pure.DI generates the rest from the implementations.
internal partial interface IArchiveDetector
{
    ArchiveDetection? DetectArchive(string filePath);
    ArchiveDetection? DetectArchive(string filePath, ReaderOptions? readerOptions);
    ArchiveDetection? DetectArchive(Stream stream);
    ArchiveDetection? DetectArchive(Stream stream, ReaderOptions? readerOptions);
    T FindFactory<T>(FileInfo fileInfo, ReaderOptions readerOptions)
        where T : SharpCompress.Factories.IFactory;
    T FindFactory<T>(Stream stream, ReaderOptions readerOptions)
        where T : SharpCompress.Factories.IFactory;
    SharpCompress.Factories.IFactory? TryFindFactory(Stream stream, ReaderOptions readerOptions);
    ArchiveDetection? TryDetectArchive(Stream stream, ReaderOptions readerOptions);
}

internal partial interface IArchiveInspector
{
    ArchiveInformation? InspectArchive(string filePath);
    ArchiveInformation? InspectArchive(string filePath, ReaderOptions? readerOptions);
    ArchiveInformation? InspectArchive(Stream stream);
    ArchiveInformation? InspectArchive(Stream stream, ReaderOptions? readerOptions);
    ArchiveInformation? InspectArchive(
        IReadOnlyList<FileInfo> fileInfos,
        ReaderOptions? readerOptions = null
    );
    ArchiveInformation? InspectArchive(
        IReadOnlyList<Stream> streams,
        ReaderOptions? readerOptions = null
    );
}

